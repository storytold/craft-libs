"""Generates src/script_autonyms.rs: each script's name in its main language (CLDR).

Run from the repository root:
    uv run --with babel==2.17.0 python crates/font-manager/tools/gen_script_autonyms.py
"""
import glob, gzip, json, re
import babel
from babel import Locale
from babel.core import get_global

CLDR = "47"  # shipped by babel 2.17.0
OUT = "crates/font-manager/src/script_autonyms.rs"

ids = set()
for path in glob.glob("crates/font-store/index/indexes/*.json.gz"):
    with gzip.open(path) as f:
        ids |= {s["id"] for s in json.load(f)["scripts"]}

likely = get_global("likely_subtags")
rows = []
for sid in sorted(ids - {"Latn"}):
    sub = likely.get(f"und_{sid}")
    if not sub:
        continue
    lang = sub.split("_")[0]
    try:
        # The script's own locale (zh_Hant_TW, not zh), so Hant is named in Traditional Chinese.
        own = Locale.parse(sub)
        # For Han, the name of the written language ("简体中文") reads better than the script's.
        name = own.languages.get(f"{lang}_{sid}") if sid in ("Hans", "Hant") else None
        name = name or own.scripts.get(sid)
    except Exception:
        continue
    if not name or re.fullmatch(r"[\x00-ɏ]+", name):
        continue  # missing, or Latin fallback text
    rows.append((sid, name))

lines = [
    "// Generated by tools/gen_script_autonyms.py; do not edit.",
    f"// Script names in their main language, from Unicode CLDR {CLDR} (babel {babel.__version__}).",
    "// Copyright Unicode, Inc. Distributed under the Unicode License v3 (https://www.unicode.org/license.txt).",
    "",
    "/// (script ID, name of the script in its main language), sorted by ID.",
    "pub(crate) const SCRIPT_AUTONYMS: &[(&str, &str)] = &[",
]
lines += [f"    ({json.dumps(s)}, {json.dumps(n, ensure_ascii=False)})," for s, n in rows]
lines += ["];", ""]
open(OUT, "w").write("\n".join(lines))
print(len(rows), "entries")
