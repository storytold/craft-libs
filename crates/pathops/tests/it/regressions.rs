/// Area identities between the four boolean operations of `a` and `b`.
fn assert_identities(a: &BezPath, b: &BezPath) {
    let op = |p: &BezPath, q: &BezPath, op| area(&boolean(p, NZ, q, NZ, op), NZ);
    let (aa, ab) = (area(a, NZ), area(b, NZ));
    let (u, i, x) = (op(a, b, BoolOp::Union), op(a, b, BoolOp::Intersect), op(a, b, BoolOp::Xor));
    let (d1, d2) = (op(a, b, BoolOp::Difference), op(b, a, BoolOp::Difference));
    let tol = 1e-6;
    assert!(close(d1 + d2, x, tol), "a−b {d1} + b−a {d2} != xor {x}");
    assert!(close(u - i, x, tol), "union {u} − intersection {i} != xor {x}");
    assert!(close(u + i, aa + ab, tol), "union {u} + intersection {i} != {aa} + {ab}");
    assert!(close(d1 + i, aa, tol), "a−b {d1} + intersection {i} != a {aa}");
    assert!(close(d2 + i, ab, tol), "b−a {d2} + intersection {i} != b {ab}");
}

