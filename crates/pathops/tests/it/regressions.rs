/// The root cause in isolation: a strip whose top edge rises by less than the sweep tolerance
/// (1e-6 here) and ends level with the point where an arc meets a horizontal edge of a second
/// contour. Every tilt must keep the strip's full area.
#[test]
fn almost_horizontal_edge_meeting_an_arc_end() {
    for dy in [1e-14, 1e-12, 1e-10, 1e-8, 1e-7, 5e-7, 9e-7] {
        let svg = format!("M10,10 L20,10 L20,16 C19,18 18,19 17,20 L11,20 Z M0,21 L0,20 L11,20 L13,20.9 L16,{} L37,20 L37,21 Z", 20.0 - dy);
        let bp = BezPath::from_svg(&svg).unwrap();
        // The contours overlap by at most a `dy`-thin sliver (and levelling the edge moves it by
        // `dy`), so the filled area is the plain (Green's theorem) area up to `dy` × its length.
        let want = bp.area().abs();
        let got = area(&bp, NZ);
        assert!((got - want).abs() <= dy * 40.0, "rise {dy}: area {got}, want {want}");
    }
}

/// `polygon_area_matches_shoelace` once drew this "star" polygon, whose wide angular step made it
/// cross itself (the strategy now rejects those): its shoelace area cancels across the crossing,
/// while the filled area is that of the two loops.
#[test]
fn self_crossing_quad_fills_both_loops() {
    let [p0, p1, p2, p3]: [kurbo::Point; 4] = [
        (43.48211493626725, 43.58815768474916),
        (39.45699865107951, 58.097908614334145),
        (56.35982114265447, 23.14196428649071),
        (72.23596128912416, 39.99999999999999),
    ]
    .map(Into::into);
    // Where p1→p2 crosses p3→p0.
    let (d1, d2) = (p2 - p1, p0 - p3);
    let x = p1 + d1 * ((p3 - p1).cross(d2) / d1.cross(d2));
    let tri = |a: kurbo::Point, b: kurbo::Point, c: kurbo::Point| (b - a).cross(c - a).abs() / 2.0;
    let want = tri(p0, p1, x) + tri(x, p2, p3);
    let got = area(&poly(&[p0, p1, p2, p3].map(|p| (p.x, p.y))), NZ);
    assert!(close(got, want, 1e-9), "area {got}, want {want}");
}

/// VectorCraft issue 5478: an operand that crosses itself (`b`), meeting another along its crossings: the sweep
/// gave each operation a wrong area (union 5.5, intersection 1.5, difference 3, xor 4), so
/// union + intersection was 7 where |a| + |b| is 5.5. The exact areas, under both fill rules.
#[test]
fn a_self_crossing_operand_gets_the_exact_areas() {
    let a = poly(&[(3.0, 1.0), (3.0, 3.0), (0.0, 1.0)]);
    let b = poly(&[(3.0, 0.0), (0.0, 2.0), (3.0, 2.0), (0.0, 0.0), (0.0, 1.0)]);
    for rule in [NZ, FillRule::EvenOdd] {
        assert!(close(area(&a, rule), 3.0, 1e-9) && close(area(&b, rule), 2.5, 1e-9), "{rule:?}");
        for (op, want) in [(BoolOp::Union, 4.375), (BoolOp::Intersect, 1.125), (BoolOp::Difference, 1.875), (BoolOp::Xor, 3.25)] {
            let got = area(&boolean(&a, rule, &b, rule, op), NZ);
            assert!(close(got, want, 1e-6), "{op:?} {rule:?}: {got}, want {want}");
            let tried = try_boolean(&a, rule, &b, rule, op, DEFAULT_PRECISION).unwrap();
            assert!(close(area(&tried, NZ), want, 1e-6), "try_boolean {op:?} {rule:?}");
        }
    }
}
