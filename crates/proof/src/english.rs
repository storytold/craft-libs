//! English spelling never goes unchecked. Its words come from the first of these that is there:
//!
//! 1. **Embedded**: the Moby word list embedded from craft-i18n at build time (`CRAFT_I18N_DIR`,
//!    see `build.rs`). When it is there, nothing in this module is used.
//! 2. **System Hunspell**: a Hunspell `.aff`/`.dic` pair for the run's own English found by
//!    [`crate::hunspell`] (`en_US` for American, `en_GB` for British, `en_CA` for Canadian
//!    English; each name in the dictionaries folder and then the system locations before the
//!    next name; none on the web). Another English's dictionary is never used: it would mark this
//!    English's spellings (`colour` in an `en_US` one), so without its own dictionary an English
//!    uses the built-in list, which has both spellings. A file that can't be read is skipped for
//!    the next name or folder, and one file is read once for every English that uses it.
//!    Directives that only matter for other languages (compounding, output conversion) are
//!    ignored ([`crate::hunspell::load_english`]).
//! 3. **Built-in word list**: [`WORDS`], the whole public-domain Moby word list compiled into
//!    the crate (without its break points), with WordCraft's own supplement of modern words
//!    ([`EXTRA`]) and the usual inflections. A word it doesn't know is misspelled, as with the
//!    embedded list.
//!
//! A Hunspell dictionary that is there but can't be read (unsupported encoding, too large, a
//! parse error, no words) is skipped, and its reason is reported by
//! [`crate::dictionary_load_error`]. Non-English text is never checked against any of these.

use std::path::{Path, PathBuf};
use std::sync::{Arc, OnceLock, PoisonError, RwLock};

use crate::affix::AffixDict;
use crate::dict::Dictionary;
use crate::{Options, ProofLang};

/// The English word list built into the crate (`data/en-words.dic`, [`Dictionary`]'s format with
/// no break points): every word of the public-domain Moby Hyphenator II list by Grady Ward
/// (generated by `examples/en_words.rs` from craft-i18n's `en-us.dic`).
const WORDS: &[u8] = include_bytes!("../data/en-words.dic");

/// WordCraft's supplement of common modern words the Moby list lacks (`data/en-extra.txt`, a copy
/// of craft-i18n's `language-data/en-us/en-extra.txt`, MIT OR Apache-2.0): one lowercase base
/// form per line, `#` comments. Used when the Language data doesn't embed its own copy.
pub(crate) const EXTRA: &str = include_str!("../data/en-extra.txt");

/// Longest word (in characters) suggestions are looked for: longer ones get none, which keeps
/// the edits tried per word bounded.
const MAX_SUGGEST_CHARS: usize = 32;

/// Most Hunspell `.aff`/`.dic` pairs tried for one English before giving up on Hunspell.
const MAX_CANDIDATES: usize = 8;

/// Where English spelling comes from now ([`crate::english_source`]).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum EnglishSource {
    /// The Moby word list embedded from craft-i18n at build time.
    Embedded,
    /// An English Hunspell dictionary from the dictionaries folder or the system: its `.dic` file.
    Hunspell(PathBuf),
    /// The Moby word list built into the crate: a word it doesn't know is misspelled.
    CoreList,
}

/// The words of [`WORDS`] (decoded on first use; empty if they fail to decode, which a test rules
/// out).
fn words() -> &'static Dictionary {
    static W: OnceLock<Dictionary> = OnceLock::new();
    W.get_or_init(|| {
        Dictionary::from_bytes(WORDS).unwrap_or_else(|e| {
            log::error!("built-in English word list: {e}");
            Dictionary::default()
        })
    })
}

/// Is `w` (lower case) a word of the built-in list?
pub(crate) fn word_list_contains(w: &str) -> bool {
    words().get(w).is_some()
}

/// Hunspell file names of `lang`'s own dictionary, the usual one first. Only its own: another
/// English's dictionary would mark its spellings, which the built-in list doesn't.
fn names(lang: ProofLang) -> &'static [&'static str] {
    match lang {
        ProofLang::EnGb => &["en_GB", "en-GB"],
        ProofLang::EnCa => &["en_CA", "en-CA"],
        _ => &["en_US", "en-US"],
    }
}

/// The slot of each English in [`State::slots`].
fn slot(lang: ProofLang) -> usize {
    match lang {
        ProofLang::EnGb => 1,
        ProofLang::EnCa => 2,
        _ => 0,
    }
}

/// A loaded Hunspell dictionary and its `.dic` file; `None` when none could be loaded.
type Loaded = Option<(Arc<AffixDict>, PathBuf)>;

/// The English Hunspell dictionaries, under one lock.
struct State {
    /// Per English (see [`slot`]): `None` until first use, then what was found.
    slots: [Option<Loaded>; 3],
    /// Every `.dic` file read, so Englishes that use the same file share one copy.
    files: Vec<(PathBuf, Arc<AffixDict>)>,
    /// Counts reloads, so a load that started before one is not kept.
    reloads: u64,
}

impl State {
    const fn new() -> Self {
        State { slots: [None, None, None], files: Vec::new(), reloads: 0 }
    }
}

static HUNSPELL: RwLock<State> = RwLock::new(State::new());

/// Why the embedded word list failed to decode, if it did.
static EMBEDDED_ERROR: OnceLock<String> = OnceLock::new();

/// Remember that the embedded word list is there but failed to decode (English then uses the
/// next source).
pub(crate) fn note_embedded_error(e: String) {
    log::error!("embedded English word list: {e}; English spelling falls back to Hunspell or the built-in word list");
    let _ = EMBEDDED_ERROR.set(e);
}

/// The English Hunspell dictionary for `lang` (read on first use).
fn hunspell(lang: ProofLang) -> Loaded {
    let i = slot(lang);
    let reloads = {
        let s = HUNSPELL.read().unwrap_or_else(PoisonError::into_inner);
        if let Some(Some(found)) = s.slots.get(i) {
            return found.clone();
        }
        s.reloads
    };
    let (loaded, error) = load(lang);
    keep(&HUNSPELL, i, reloads, loaded, || note_error(lang, error))
}

/// Keep in `state` what the load of slot `i`, started after `reloads` reloads, found, and `note`
/// its load error. If the folder was reloaded since, the load may have read the old folder: it
/// serves this one check, its error isn't noted, and the next check loads again.
fn keep(state: &RwLock<State>, i: usize, reloads: u64, loaded: Loaded, note: impl FnOnce()) -> Loaded {
    let mut s = state.write().unwrap_or_else(PoisonError::into_inner);
    if s.reloads != reloads {
        return match s.slots.get(i) {
            Some(Some(found)) => found.clone(),
            _ => loaded,
        };
    }
    note();
    let loaded = loaded.map(|(d, dic)| {
        // Another English may have read the same file meanwhile: share its copy.
        let d = match s.files.iter().find(|(p, _)| *p == dic) {
            Some((_, shared)) => shared.clone(),
            None => {
                s.files.push((dic.clone(), d.clone()));
                d
            }
        };
        (d, dic)
    });
    // Another thread may have filled it meanwhile: that one wins.
    match s.slots.get_mut(i) {
        Some(slot) => slot.get_or_insert(loaded).clone(),
        None => loaded,
    }
}

/// The dictionary of the `.dic` file `dic` in `state`, if an English already read it.
fn already_read(state: &RwLock<State>, dic: &Path) -> Option<Arc<AffixDict>> {
    state.read().unwrap_or_else(PoisonError::into_inner).files.iter().find(|(p, _)| p == dic).map(|(_, d)| d.clone())
}

/// Forget what `state` holds, so the next check looks again.
fn forget(state: &RwLock<State>) {
    let mut s = state.write().unwrap_or_else(PoisonError::into_inner);
    s.slots = [None, None, None];
    s.files.clear();
    s.reloads = s.reloads.wrapping_add(1);
}

/// The key load errors of `lang` are kept under ([`crate::hunspell::load_error`]).
fn key(lang: ProofLang) -> &'static str {
    names(lang).first().copied().unwrap_or("en_US")
}

/// Read the first Hunspell pair of `lang`'s own that loads, trying each name in each folder
/// ([`crate::hunspell::candidates`]), with the first failure before it (the file `lang` would
/// rather use), for [`note_error`].
fn load(lang: ProofLang) -> (Loaded, Option<(PathBuf, String)>) {
    let candidates = crate::hunspell::candidates(names(lang));
    if candidates.is_empty() {
        log::info!("English spelling: no Hunspell {} dictionary installed; using the built-in word list", key(lang));
        return (None, None);
    }
    let mut first_error: Option<(PathBuf, String)> = None;
    for (aff, dic) in candidates.into_iter().take(MAX_CANDIDATES) {
        let loaded = match already_read(&HUNSPELL, &dic) {
            Some(d) => Ok(d),
            None => crate::hunspell::load_english(&aff, &dic)
                .and_then(|d| if d.is_empty() { Err(format!("{}: no words", dic.display())) } else { Ok(d) })
                .map(Arc::new),
        };
        match loaded {
            Ok(d) => return (Some((d, dic)), first_error),
            Err(e) => {
                log::warn!("English spelling: {e}; trying the next dictionary");
                first_error.get_or_insert((dic, e));
            }
        }
    }
    log::warn!("English spelling: no {} Hunspell dictionary could be read; using the built-in word list", key(lang));
    (None, first_error)
}

/// Remember `lang`'s load error ([`crate::dictionary_load_error`]), or that it has none.
fn note_error(lang: ProofLang, error: Option<(PathBuf, String)>) {
    match error {
        Some((dic, e)) => {
            let _ = crate::hunspell::note_load::<()>(key(lang), &dic, Err(e));
        }
        None => crate::hunspell::clear_load_error(key(lang)),
    }
}

/// Forget the loaded dictionaries, so the next check looks for them again (the dictionaries
/// folder changed).
pub(crate) fn reload() {
    forget(&HUNSPELL);
    for lang in [ProofLang::En, ProofLang::EnGb, ProofLang::EnCa] {
        crate::hunspell::clear_load_error(key(lang));
    }
}

/// Where the spelling of `lang` (an English) comes from now. Reads the Hunspell dictionary once
/// when there is no embedded data (it is cached afterwards).
pub(crate) fn source(lang: ProofLang) -> EnglishSource {
    if crate::english_data() {
        EnglishSource::Embedded
    } else {
        hunspell(lang).map_or(EnglishSource::CoreList, |(_, dic)| EnglishSource::Hunspell(dic))
    }
}

/// Why a source of `lang`'s spelling failed to load: the embedded word list, or (without it) the
/// Hunspell dictionary found for it. Reads nothing itself.
pub(crate) fn load_error(lang: ProofLang) -> Option<String> {
    if let Some(e) = EMBEDDED_ERROR.get() {
        return Some(e.clone());
    }
    if crate::english_data() {
        return None;
    }
    crate::hunspell::load_error(key(lang)).map(|(_, reason)| reason)
}

/// Is `word` spelled right in `lang` (an English) when no word list is embedded: against the
/// Hunspell dictionary, or else the built-in word list.
pub(crate) fn is_correct(word: &str, lang: ProofLang, opts: &Options) -> bool {
    let w = word.trim_matches(|c: char| !c.is_alphanumeric() && c != '\'' && c != '’').trim_matches(['\'', '’']);
    if crate::accepted_by_options(w, opts) || !w.chars().any(|c| c.is_ascii_alphabetic()) {
        return true; // other scripts: not English
    }
    let w = w.replace('’', "'");
    match hunspell(lang) {
        Some((d, _)) => hunspell_correct(&d, &w),
        None => list_correct(&w),
    }
}

/// Against an installed English Hunspell dictionary: the word, or each part of a hyphenated one.
fn hunspell_correct(d: &AffixDict, w: &str) -> bool {
    let known = |p: &str| p.chars().count() <= 1 || d.check(p) || crate::in_user_dictionary(&p.to_lowercase());
    known(w) || (w.contains('-') && w.split('-').filter(|p| !p.is_empty()).all(known))
}

/// Against the built-in word list: its words and their inflections, or each part of a
/// hyphenated word. Anything else is misspelled. (Should the list fail to decode, nothing is
/// marked rather than everything.)
fn list_correct(w: &str) -> bool {
    if words().is_empty() {
        return true;
    }
    let lower = w.to_lowercase();
    crate::known_in_word_list(&lower) || (lower.contains('-') && lower.split('-').filter(|p| !p.is_empty()).all(crate::known_in_word_list))
}

/// Spelling suggestions in `lang` (an English) when no word list is embedded: from the Hunspell
/// dictionary, or else the built-in word list.
pub(crate) fn suggest(word: &str, max: usize, lang: ProofLang) -> Vec<String> {
    match hunspell(lang) {
        Some((d, _)) => crate::cs::suggest::suggest_in(&d, word, max),
        None => list_suggest(word, max),
    }
}

/// Letters an edit may add or put in a word's place.
const ALPHABET: &str = "abcdefghijklmnopqrstuvwxyz'";

/// Are `a` and `b` neighbouring keys on a QWERTY keyboard? (A typing slip: `wprd` for `word`.)
fn neighbour_keys(a: char, b: char) -> bool {
    const ROWS: [&str; 3] = ["qwertyuiop", "asdfghjkl", "zxcvbnm"];
    // Each row sits half a key right of the one above: x in half keys.
    let at = |c: char| ROWS.iter().enumerate().find_map(|(r, row)| row.find(c).map(|col| (r as i64, 2 * col as i64 + r as i64)));
    match (at(a), at(b)) {
        (Some((ra, xa)), Some((rb, xb))) => (ra == rb && (xa - xb).abs() == 2) || ((ra - rb).abs() == 1 && (xa - xb).abs() <= 1),
        _ => false,
    }
}

/// A suggestion's rank, lowest first: not a swap, not a common word, not a neighbouring key, not
/// the same first letter, the difference in length.
type Rank = (bool, bool, bool, bool, usize);

/// How an edit changed the word, for ranking.
#[derive(Clone, Copy)]
enum Edit {
    /// Two neighbouring letters swapped.
    Swap,
    /// One letter changed from the first to the second.
    Change(char, char),
    /// One letter added or missing.
    Other,
}

/// Suggestions from the built-in word list: the words one edit away (two neighbouring letters
/// swapped, one letter missing, added or changed), looked up in the list rather than compared
/// with every word, so the cost is bounded by the word's length (at most
/// [`MAX_SUGGEST_CHARS`]). Ranked: swaps first (`recieve` → `receive`), then the common words
/// (`hte` → `the` before `het`), a letter changed to a neighbouring key's, the same first letter,
/// the nearest in length. One-letter words other than `a` and `I` are never suggested.
fn list_suggest(word: &str, max: usize) -> Vec<String> {
    let lower = word.to_lowercase().replace('’', "'");
    let target: Vec<char> = lower.chars().collect();
    let n = target.len();
    if max == 0 || n == 0 || n > MAX_SUGGEST_CHARS {
        return Vec::new();
    }
    let mut found: Vec<(Rank, String)> = Vec::new();
    let mut tried = std::collections::HashSet::new();
    let mut consider = |c: Vec<char>, edit: Edit| {
        let s: String = c.iter().collect();
        if (c.len() < 2 && !matches!(s.as_str(), "a" | "i")) || s == lower || !tried.insert(s.clone()) || !crate::known_in_word_list(&s) {
            return;
        }
        let key = (
            !matches!(edit, Edit::Swap),
            !crate::is_common_word(&s),
            !matches!(edit, Edit::Change(from, to) if neighbour_keys(from, to)),
            c.first() != target.first(),
            c.len().abs_diff(n),
        );
        found.push((key, s));
    };
    for i in 1..n {
        let mut c = target.clone();
        c.swap(i - 1, i);
        consider(c, Edit::Swap);
    }
    for i in 0..n {
        let mut c = target.clone();
        c.remove(i);
        consider(c, Edit::Other);
    }
    for i in 0..=n {
        for a in ALPHABET.chars() {
            if let Some(&from) = target.get(i) {
                let mut c = target.clone();
                if let Some(l) = c.get_mut(i) {
                    *l = a;
                }
                consider(c, Edit::Change(from, a));
            }
            let mut c = target.clone();
            c.insert(i, a);
            consider(c, Edit::Other);
        }
    }
    found.sort();
    found.into_iter().take(max).map(|(_, w)| crate::match_case(word, w)).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn built_in_list_is_the_whole_moby_list() {
        let d = words();
        assert!(d.len() > 150_000, "{}", d.len());
        assert!(d.iter().all(|(w, m)| m == 0 && !w.is_empty() && w.chars().all(|c| !c.is_uppercase())));
        assert!(WORDS.len() < 400 * 1024, "{} bytes", WORDS.len());
        let extra: Vec<&str> = EXTRA.lines().filter(|l| !l.is_empty() && !l.starts_with('#')).collect();
        assert!(extra.len() > 100 && extra.windows(2).all(|p| p[0] < p[1]), "the supplement is sorted");
    }

    /// The built-in list knows right words, the rare and the modern ones included, and marks
    /// every word it doesn't know (craft-libs#482 review: the old core list let any unknown word
    /// through unless it was a near miss of a common one, and marked right words that were).
    #[test]
    fn built_in_list_marks_unknown_words_only() {
        for w in [
            "the",
            "The",
            "houses",
            "running",
            "looked",
            "happily",
            "kindness",
            "Received",
            "well-known",
            "photosynthesis",
            "fiber",
            "theater",
            "organize",
            "budget",
            "phone",
            "people's",
            "wont",
            "cant",
            // WordCraft's supplement.
            "login",
            "blog",
            "email",
            "emails",
        ] {
            assert!(list_correct(w), "{w} is not marked");
        }
        for w in ["teh", "Teh", "abd", "ur", "recieved", "definately", "seperate", "ocurred", "becuase", "peopel", "beautifull", "zxqv", "Jarndycey"]
        {
            assert!(!list_correct(w), "{w} is marked");
        }
        assert!(!list_correct("well-knwon"), "each part of a compound is checked");
    }

    #[test]
    fn built_in_list_suggests_one_edit_away() {
        assert_eq!(list_suggest("becuase", 3).first().map(String::as_str), Some("because"));
        assert_eq!(list_suggest("Becuase", 3).first().map(String::as_str), Some("Because"));
        assert_eq!(list_suggest("hte", 3).first().map(String::as_str), Some("the"));
        assert_eq!(list_suggest("recieve", 3).first().map(String::as_str), Some("receive"));
        assert_eq!(list_suggest("wprd", 3).first().map(String::as_str), Some("word"), "a neighbouring key");
        assert!(list_suggest("é", 5).iter().all(|s| s.chars().count() > 1 || s == "a" || s == "i"), "{:?}", list_suggest("é", 5));
        assert!(list_suggest("x", 5).iter().all(|s| s.chars().count() > 1 || s == "a" || s == "i"), "{:?}", list_suggest("x", 5));
        assert!(!neighbour_keys('q', 's') && neighbour_keys('q', 'a') && neighbour_keys('o', 'p') && !neighbour_keys('é', 'e'));
        assert!(list_suggest("definately", 5).contains(&"definitely".to_string()));
        assert!(list_suggest("", 5).is_empty() && list_suggest("becuase", 0).is_empty());
        assert!(list_suggest(&"a".repeat(MAX_SUGGEST_CHARS + 1), 5).is_empty());
    }

    /// Suggestions look words up rather than scanning the list: the longest word is still quick.
    #[test]
    fn built_in_list_suggestions_are_bounded() {
        let _ = words();
        let word: String = "qwertyuiopasdfghjklzxcvbnm".chars().cycle().take(MAX_SUGGEST_CHARS).collect();
        let start = std::time::Instant::now();
        for _ in 0..10 {
            let _ = list_suggest(&word, 5);
        }
        assert!(start.elapsed() < std::time::Duration::from_secs(5), "{:?}", start.elapsed());
    }

    /// craft-libs#482 review: a load that started before a reload (the dictionaries folder
    /// changed) serves its own check but isn't kept, so the next check reads the new folder; a
    /// load after it is kept, and shared with the Englishes that read the same file.
    #[test]
    fn a_load_from_before_a_reload_is_not_kept() {
        let state = RwLock::new(State::new());
        let noted = std::cell::Cell::new(false);
        let dict = || Arc::new(AffixDict::from_hunspell("", "1\nzzyzx\n", &[]).unwrap());
        let file = PathBuf::from("/old/folder/en_US.dic");
        let before = state.read().unwrap().reloads;
        forget(&state); // The folder changes while the load runs.
        let got = keep(&state, slot(ProofLang::En), before, Some((dict(), file.clone())), || noted.set(true));
        assert_eq!(got.map(|(_, p)| p), Some(file.clone()), "the stale load still answers its own check");
        assert!(state.read().unwrap().slots.iter().all(Option::is_none), "but it isn't kept");
        assert!(!noted.get(), "nor is its load error");
        assert!(already_read(&state, &file).is_none());
        let now = state.read().unwrap().reloads;
        let a = keep(&state, slot(ProofLang::En), now, Some((dict(), file.clone())), || noted.set(true)).unwrap();
        assert!(noted.get());
        let b = keep(&state, slot(ProofLang::EnGb), now, Some((dict(), file.clone())), || {}).unwrap();
        assert!(Arc::ptr_eq(&a.0, &b.0), "one copy of a file for every English that reads it");
        assert!(already_read(&state, &file).is_some());
        forget(&state);
        assert!(already_read(&state, &file).is_none() && state.read().unwrap().slots.iter().all(Option::is_none));
    }
}
