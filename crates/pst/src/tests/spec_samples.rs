#[test]
fn sample_header_checks_out() {
    // 3.2: dwCRCPartial 0x379aa90e, dwCRCFull 0x1fd283d6.
    assert_eq!(crc32(&HEADER[8..479]), 0x379A_A90E);
    assert_eq!(crc32(&HEADER[8..524]), 0x1FD2_83D6);
    let h = Header::parse(HEADER).unwrap();
    assert_eq!(h.format, Format::Unicode);
    assert_eq!(h.version, 23);
    assert_eq!(h.encryption, Encryption::Permute);
    assert_eq!(h.file_eof, 0x9F_2400);
    assert_eq!((h.nbt.bid, h.nbt.ib), (0x24B, 0x90_5200));
    assert_eq!((h.bbt.bid, h.bbt.ib), (0x253, 0x90_0A00));
}

#[test]
fn sample_page_signatures() {
    // 3.3 and 3.5: the intermediate page at 0x8200 (bid 0x206) and the BBT leaf at 0x900200
    // (bid 0x246) carry 0x8006 and 0x00D6.
    assert_eq!(signature(0x8200, 0x206), 0x8006);
    assert_eq!(signature(0x90_0200, 0x246), 0x00D6);
}

#[test]
fn permutation_tables_undo_each_other() {
    let (r, s, i) = tables();
    for b in 0..=255u8 {
        assert_eq!(i[usize::from(r[usize::from(b)])], b);
        assert_eq!(s[usize::from(s[usize::from(b)])], b);
    }
    for method in [Encryption::Permute, Encryption::Cyclic] {
        let original: Vec<u8> = (0..=255u8).cycle().take(1000).collect();
        let mut data = original.clone();
        encode(method, &mut data, 0x1234_5678);
        assert_ne!(data, original);
        decode(method, &mut data, 0x1234_5678);
        assert_eq!(data, original);
    }
}

#[test]
fn sample_message_store_heap() {
    // 3.8–3.10: the message store's PC of a Unicode file named "UNICODE1".
    let heap = Heap::new(vec![STORE_HEAP.to_vec()]).unwrap();
    assert_eq!(heap.client, 0xBC);
    assert_eq!(heap.user_root, 0x20);
    let node = crate::ltp::NodeData { heap, subnodes: Default::default() };
    let records = crate::ltp::pc_records(&node).unwrap();
    assert_eq!(records.len(), 11);
    let ids: Vec<u16> = records.iter().map(|r| r.0).collect();
    assert!(ids.contains(&0x3001) && ids.contains(&0x67FF) && ids.contains(&0x35E0));
    let (_, ty, raw) = records.iter().find(|r| r.0 == 0x3001).copied().unwrap();
    assert_eq!(ty, 0x001F);
    let name = crate::prop::stored(ty, node.heap.item(raw).unwrap()).unwrap();
    assert_eq!(name, PropValue::String("UNICODE1".into()));
    let (_, _, raw) = records.iter().find(|r| r.0 == 0x0FF9).copied().unwrap();
    assert_eq!(node.heap.item(raw).unwrap(), &[0x22, 0x9D, 0xB5, 0x0A, 0xDC, 0xD9, 0x94, 0x43, 0x85, 0xDE, 0x90, 0xAE, 0xB0, 0x7D, 0x12, 0x70]);
    let (_, _, raw) = records.iter().find(|r| r.0 == 0x35DF).copied().unwrap();
    assert_eq!(raw, 0x89);
    let (_, _, raw) = records.iter().find(|r| r.0 == 0x67FF).copied().unwrap();
    assert_eq!(raw, 0);
}

#[test]
fn sample_hierarchy_table_heap() {
    // 3.11–3.12: the root folder's hierarchy table, three rows in the heap.
    let heap = Heap::new(vec![HIERARCHY_HEAP.to_vec()]).unwrap();
    assert_eq!(heap.client, 0x7C);
    let info = heap.item(heap.user_root).unwrap();
    assert_eq!(info[1], 0x0D);
    let index = crate::bth::read(&heap, 0x20, 1000, Error::Corrupt("")).unwrap();
    let rows: Vec<(u32, u32)> =
        index.records.iter().map(|r| (u32::from_le_bytes(r[0..4].try_into().unwrap()), u32::from_le_bytes(r[4..8].try_into().unwrap()))).collect();
    assert_eq!(rows, vec![(0x2223, 2), (0x8022, 0), (0x8042, 1)]);
    let matrix = heap.item(0x80).unwrap();
    assert_eq!(matrix.len(), 3 * 55);
    // Row 0's display name (column 0x3001 at offset 8) is "Top of Personal Folders".
    let hid = u32::from_le_bytes(matrix[8..12].try_into().unwrap());
    assert_eq!(crate::bytes::utf16(heap.item(hid).unwrap()), "Top of Personal Folders");
}

