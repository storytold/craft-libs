//! The components index: every registered component type with its module and the purpose its derive recorded
//! from the doc comment, and every craft-behavior module with the first sentence of its module docs.
//!
//! The generator binary writes `docs/components-index.md` from [`components_index`] over
//! `craft_ui::testing::library_registrations()`; a trial of craft-ui compares the two.

use std::fs;
use std::path::{Path, PathBuf};

use crate::contract::{Registration, kit_module};

/// The first sentence of the first paragraph of `lines`, without its final full stop, safe inside a table cell.
fn purpose(lines: &[&str]) -> String {
    let paragraph: Vec<&str> = lines.iter().map(|line| line.trim()).take_while(|line| !line.is_empty()).collect();
    let text = paragraph.join(" ");
    let sentence = text.split_once(". ").map_or(text.as_str(), |(first, _)| first);
    sentence.trim_end_matches('.').replace('|', "\\|")
}

fn table_row(cells: &[&str]) -> String {
    format!("| {} |\n", cells.join(" | "))
}

/// The `.rs` files directly in `dir`, sorted.
fn top_level_files(dir: &Path) -> Vec<PathBuf> {
    let mut files: Vec<PathBuf> = fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|extension| extension == "rs"))
        .collect();
    files.sort();
    files
}

/// The components and patterns of `registered`: module, name, shape (`Pattern` for a pattern) and purpose, sorted.
fn registered_rows(registered: &[&'static Registration]) -> Vec<(String, String, String, String)> {
    let shown = |name: &'static str| name.rsplit_once("::").map_or(name, |(_, last)| last).to_owned();
    let components = registered
        .iter()
        .filter_map(|registration| registration.probe())
        .filter(|probe| !kit_module(probe.module))
        .map(|probe| (probe.module.to_owned(), shown(probe.type_name()), format!("{:?}", probe.shape), probe.purpose.replace('|', "\\|")));
    let patterns = registered
        .iter()
        .filter_map(|registration| registration.pattern_probe())
        .map(|probe| (probe.module.to_owned(), shown(probe.type_name()), probe.kind.label().to_owned(), probe.purpose.replace('|', "\\|")));
    let mut rows: Vec<_> = components.chain(patterns).collect();
    rows.sort();
    rows.dedup();
    rows
}

/// The types of `registered` that have no purpose: their types lack a doc comment.
pub fn types_without_purpose(registered: &[&'static Registration]) -> Vec<String> {
    registered_rows(registered)
        .into_iter()
        .filter(|(_, _, _, purpose)| purpose.is_empty())
        .map(|(module, name, _, _)| format!("{module}::{name}"))
        .collect()
}

/// The text of `docs/components-index.md` for the workspace at `root` and the types of `registered`.
pub fn components_index(root: &Path, registered: &[&'static Registration]) -> String {
    let mut out = String::from("# Built components\n\n");
    out.push_str("Generated by `cargo run -p craft-ui-gallery --bin components-index`; edit the doc comments, not this file.\n\n");

    out.push_str("## Registered types\n\n| Type | Shape | Module | Purpose |\n|---|---|---|---|\n");
    for (module, name, shape, purpose) in registered_rows(registered) {
        out.push_str(&table_row(&[&format!("`{name}`"), &shape, &format!("`{module}`"), &purpose]));
    }

    out.push_str("\n## Behaviours\n\n| Module | Purpose |\n|---|---|\n");
    for file in top_level_files(&root.join("crates/behavior/src")) {
        let stem = file.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default();
        if matches!(stem.as_str(), "lib" | "main") {
            continue;
        }
        let Ok(text) = fs::read_to_string(&file) else { continue };
        let docs: Vec<&str> = text.lines().take_while(|line| line.starts_with("//!")).map(|line| &line[3..]).collect();
        out.push_str(&table_row(&[&format!("`craft_behavior::{stem}`"), &purpose(&docs)]));
    }
    out
}
